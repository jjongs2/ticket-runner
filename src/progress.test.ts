import { describe, expect, it } from "vitest";
import {
  PROGRESS_MARKER,
  Progress,
  findProgressComment,
  progressComment,
  tokenCount,
} from "./progress.js";
import type { IssueComment } from "./ports/tracker.js";
import { HANDOFF_MARKER, HANDOFF_TAKEN_LINE } from "./templates.js";
import { FakeTracker } from "./testing/fakes.js";

const TICKET = 2;
const BRANCH = "agent/2-progress-comment";
/** The version reporting, which every header the Run writes carries. */
const VERSION = "0.4.0+331d79c";
/** What a cloud Host appends to every comment written through `gh`. */
const CLOUD_FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_";

function progress(
  tracker: FakeTracker,
  comments: IssueComment[] = [],
  runId = "run-1",
): Progress {
  return new Progress({
    tracker,
    ticket: TICKET,
    version: VERSION,
    runId,
    branch: BRANCH,
    comments,
  });
}

function body(tracker: FakeTracker): string {
  return tracker.issue(TICKET).comments.at(-1)?.body ?? "";
}

describe("the comment body", () => {
  it("starts with the marker and names the version, the Run and the branch", () => {
    const rendered = progressComment({
      version: VERSION,
      runId: "run-1",
      branch: BRANCH,
      rows: [],
    });

    expect(rendered.split("\n").slice(0, 2)).toEqual([
      PROGRESS_MARKER,
      `**ticket-runner** \`${VERSION}\` · run \`run-1\` · \`${BRANCH}\``,
    ]);
  });

  it("carries the columns Stage, Outcome, Context and Duration", () => {
    const rendered = progressComment({
      version: VERSION,
      runId: "run-1",
      branch: BRANCH,
      rows: [],
    });

    expect(rendered).toContain("| Stage | Outcome | Context | Duration |");
    expect(rendered).not.toContain("Turns");
  });

  it("writes one row per Stage, in the order they finished", () => {
    const rendered = progressComment({
      version: VERSION,
      runId: "run-1",
      branch: BRANCH,
      rows: [
        {
          point: "implement",
          outcome: "✅ committed",
          context: { tokens: 107_600 },
          durationMs: 1_200_000,
        },
        { point: "ci", outcome: "✅ passed", durationMs: 120_000 },
      ],
    });

    expect(rendered).toContain("| implement | ✅ committed | 107.6K | 20m 0s |");
    expect(rendered).toContain("| ci | ✅ passed | – | 2m 0s |");
  });

  it("follows the figure of a Stage whose main session compacted with ` · compacted`", () => {
    const rendered = progressComment({
      version: VERSION,
      runId: "run-1",
      branch: BRANCH,
      rows: [
        {
          point: "implement",
          outcome: "✅ committed",
          context: { tokens: 200_000, compacted: true },
          durationMs: 0,
        },
      ],
    });

    expect(rendered).toContain("| implement | ✅ committed | 200K · compacted | 0s |");
  });

  it.each([
    [0, "0"],
    [850, "850"],
    [999, "999"],
    [1_000, "1K"],
    [1_049, "1K"],
    [1_050, "1.1K"],
    [107_600, "107.6K"],
    [107_650, "107.7K"],
    [200_000, "200K"],
    [999_949, "999.9K"],
    [999_950, "1M"],
    [1_000_000, "1M"],
    [1_049_999, "1M"],
    [1_050_000, "1.1M"],
    [545_000, "545K"],
    [12_345_678, "12.3M"],
  ])("writes %i tokens as %s", (count, shown) => {
    expect(tokenCount(count)).toBe(shown);
  });

  it.each([
    [-65_000, "0s"],
    [0, "0s"],
    [400, "0s"],
    [500, "1s"],
    [40_000, "40s"],
    [59_400, "59s"],
    [59_600, "1m 0s"],
    [65_000, "1m 5s"],
    [3_599_600, "1h 0m 0s"],
    [3_605_000, "1h 0m 5s"],
    [11_735_000, "3h 15m 35s"],
  ])("gives a duration of %i ms as %s, the way GitHub Actions does", (durationMs, shown) => {
    const rendered = progressComment({
      version: VERSION,
      runId: "run-1",
      branch: BRANCH,
      rows: [{ point: "ci", outcome: "✅ passed", durationMs }],
    });

    expect(rendered).toContain(`| ci | ✅ passed | – | ${shown} |`);
  });

  it("repeats a Stage that ran twice rather than overwriting its row", () => {
    const rendered = progressComment({
      version: VERSION,
      runId: "run-1",
      branch: BRANCH,
      rows: [
        { point: "ci", outcome: "❌ `npm test` failed", durationMs: 0 },
        { point: "fix", outcome: "✅ committed", context: { tokens: 4_000 }, durationMs: 0 },
        { point: "ci", outcome: "✅ passed", durationMs: 0 },
      ],
    });

    expect(rendered.match(/^\| ci \|/gm)).toHaveLength(2);
  });

  it("dashes the cells a row has no answer for", () => {
    const rendered = progressComment({
      version: VERSION,
      runId: "run-1",
      branch: BRANCH,
      rows: [{ point: "merge", outcome: "✅ #100" }],
    });

    expect(rendered).toContain("| merge | ✅ #100 | – | – |");
  });

  it("escapes a pipe in an outcome so it cannot break the table", () => {
    const rendered = progressComment({
      version: VERSION,
      runId: "run-1",
      branch: BRANCH,
      rows: [{ point: "ci", outcome: "❌ `npm test | tee log` failed", durationMs: 0 }],
    });

    expect(rendered).toContain("| ci | ❌ `npm test \\| tee log` failed | – | 0s |");
  });
});

describe("finding the comment again", () => {
  it("finds the one carrying the marker", () => {
    const found = findProgressComment([
      { id: "1", body: "a human said something" },
      { id: "2", body: `${PROGRESS_MARKER}\n**ticket-runner** · run \`run-0\`` },
    ]);

    expect(found?.id).toBe("2");
  });

  it("ignores a comment that only mentions the marker further down", () => {
    const found = findProgressComment([
      { id: "1", body: `the pipeline writes ${PROGRESS_MARKER} as its first line` },
    ]);

    expect(found).toBeUndefined();
  });

  it("finds nothing on a Ticket no Stage has reported on", () => {
    expect(findProgressComment([])).toBeUndefined();
  });

  it("finds the newest of several, which is the one this Run posted", () => {
    const found = findProgressComment([
      { id: "1", body: `${PROGRESS_MARKER}\nwhat a human read before the hand-off` },
      { id: "2", body: `${PROGRESS_MARKER}\nwhat the Run that took it back posted` },
    ]);

    expect(found?.id).toBe("2");
  });
});

describe("recording a Stage", () => {
  it("creates the comment on the first Stage of a Ticket", async () => {
    const tracker = new FakeTracker();
    tracker.addIssue({ number: TICKET });

    await progress(tracker).record({
      point: "implement",
      outcome: "✅ committed",
      context: { tokens: 850 },
    });

    expect(tracker.comments).toHaveLength(1);
    expect(body(tracker)).toContain("| implement | ✅ committed | 850 | – |");
  });

  it("edits that same comment on every later Stage", async () => {
    const tracker = new FakeTracker();
    tracker.addIssue({ number: TICKET });
    const recorder = progress(tracker);

    await recorder.record({ point: "implement", outcome: "✅ committed", context: { tokens: 850 } });
    await recorder.record({ point: "ci", outcome: "✅ passed", durationMs: 0 });

    expect(tracker.comments).toHaveLength(1);
    expect(tracker.updatedComments).toHaveLength(1);
    expect(body(tracker)).toContain("| implement | ✅ committed | 850 | – |");
    expect(body(tracker)).toContain("| ci | ✅ passed | – | 0s |");
  });

  it("reuses the comment an earlier Run left behind", async () => {
    const tracker = new FakeTracker();
    const issue = tracker.addIssue({ number: TICKET });
    issue.comments.push({ id: "42", body: `${PROGRESS_MARKER}\nold` });

    await progress(tracker, issue.comments).record({ point: "implement", outcome: "✅ committed" });

    expect(tracker.comments).toEqual([]);
    expect(tracker.updatedComments).toEqual([
      { id: "42", body: expect.stringContaining("| implement | ✅ committed | – | – |") },
    ]);
  });

  it("keeps an earlier Run's header and rows and writes its own below them", async () => {
    const tracker = new FakeTracker();
    const issue = tracker.addIssue({ number: TICKET });
    const earlier = progressComment({
      version: "0.5.0",
      runId: "run-0",
      branch: BRANCH,
      rows: [
        {
          point: "implement",
          outcome: "✅ committed",
          context: { tokens: 107_600 },
          durationMs: 1_260_000,
        },
      ],
    });
    issue.comments.push({ id: "42", body: earlier });

    await progress(tracker, issue.comments).record({ point: "ci", outcome: "✅ passed" });

    expect(tracker.updatedComments[0]?.body).toBe(
      [
        earlier,
        `**ticket-runner** \`${VERSION}\` · run \`run-1\` · \`${BRANCH}\``,
        "",
        "| Stage | Outcome | Context | Duration |",
        "|---|---|---|---|",
        "| ci | ✅ passed | – | – |",
        "",
      ].join("\n"),
    );
  });

  it("shows three Runs as three sections, oldest first", async () => {
    const tracker = new FakeTracker();
    const issue = tracker.addIssue({ number: TICKET });

    await progress(tracker, [], "run-1").record({ point: "implement", outcome: "⏸ rate limited" });
    await progress(tracker, issue.comments, "run-2").record({
      point: "implement",
      outcome: "✅ committed",
    });
    await progress(tracker, issue.comments, "run-3").record({ point: "ci", outcome: "✅ passed" });

    expect(tracker.comments).toHaveLength(1);
    expect([...body(tracker).matchAll(/run `(run-\d)`/g)].map((match) => match[1])).toEqual([
      "run-1",
      "run-2",
      "run-3",
    ]);
    expect(body(tracker).match(/^\| Stage \|/gm)).toHaveLength(3);
  });

  it("rewrites its own section when it is already the last one, rather than adding another", async () => {
    const tracker = new FakeTracker();
    const issue = tracker.addIssue({ number: TICKET });
    const earlier = progressComment({
      version: "0.5.0",
      runId: "run-0",
      branch: BRANCH,
      rows: [{ point: "implement", outcome: "⏸ rate limited" }],
    });
    issue.comments.push({ id: "42", body: earlier });

    await progress(tracker, issue.comments).record({ point: "implement", outcome: "✅ committed" });
    // This Run reads the Ticket again, as it does on a second pass of it.
    const again = progress(tracker, issue.comments);
    await again.record({ point: "ci", outcome: "✅ passed" });
    await again.record({ point: "verify", outcome: "❌ 1 unmet" });

    expect(tracker.comments).toEqual([]);
    expect(body(tracker).match(/run `run-1`/g)).toHaveLength(1);
    expect(body(tracker).startsWith(earlier)).toBe(true);
    expect(body(tracker)).toContain("| ci | ✅ passed | – | – |\n| verify | ❌ 1 unmet | – | – |");
  });

  it("keeps a comment an earlier version wrote as the first section, byte for byte", async () => {
    const tracker = new FakeTracker();
    const issue = tracker.addIssue({ number: TICKET });
    const single = [
      PROGRESS_MARKER,
      `**ticket-runner** \`0.4.0+331d79c\` · run \`run-0\` · \`${BRANCH}\``,
      "",
      "| Stage | Outcome | Turns | Duration |",
      "|---|---|---|---|",
      "| implement | ✅ committed | 7 | 20m |",
      "| checks | ✅ passed | – | 2m |",
      "",
    ].join("\n");
    issue.comments.push({ id: "42", body: single });

    await progress(tracker, issue.comments).record({ point: "verify", outcome: "❌ no verdict" });

    expect(body(tracker).startsWith(`${single}\n**ticket-runner** \`${VERSION}\` · run \`run-1\``)).toBe(
      true,
    );
  });

  it("carries an earlier Run's Turns column forward as written, above its own Context column", async () => {
    const tracker = new FakeTracker();
    const issue = tracker.addIssue({ number: TICKET });
    const turns = [
      PROGRESS_MARKER,
      `**ticket-runner** \`0.6.7\` · run \`run-0\` · \`${BRANCH}\``,
      "",
      "| Stage | Outcome | Turns | Duration |",
      "|---|---|---|---|",
      "| implement | ✅ committed | 301 | 37m 48s |",
      "",
    ].join("\n");
    issue.comments.push({ id: "42", body: turns });

    await progress(tracker, issue.comments).record({
      point: "verify",
      outcome: "✅ 1 met",
      context: { tokens: 95_250 },
      durationMs: 65_000,
    });

    expect(body(tracker)).toBe(
      [
        turns,
        `**ticket-runner** \`${VERSION}\` · run \`run-1\` · \`${BRANCH}\``,
        "",
        "| Stage | Outcome | Context | Duration |",
        "|---|---|---|---|",
        "| verify | ✅ 1 met | 95.3K | 1m 5s |",
        "",
      ].join("\n"),
    );
  });

  it("carries an earlier Run's whole minutes forward as written, beside its own seconds", async () => {
    const tracker = new FakeTracker();
    const issue = tracker.addIssue({ number: TICKET });
    const minutes = [
      PROGRESS_MARKER,
      `**ticket-runner** \`0.5.0\` · run \`run-0\` · \`${BRANCH}\``,
      "",
      "| Stage | Outcome | Turns | Duration |",
      "|---|---|---|---|",
      "| implement | ✅ committed | 46 | 21m |",
      "| checks | ✅ passed | – | 0m |",
      "| ci | ⏸ GitHub failure | – | 2m |",
      "",
    ].join("\n");
    issue.comments.push({ id: "42", body: minutes });

    await progress(tracker, issue.comments).record({
      point: "ci",
      outcome: "✅ passed",
      durationMs: 65_000,
    });

    expect(body(tracker).startsWith(minutes)).toBe(true);
    expect(body(tracker).endsWith("| ci | ✅ passed | – | 1m 5s |\n")).toBe(true);
  });

  it("keeps an earlier Run's header and rows without the footer a Host appended after them", async () => {
    const tracker = new FakeTracker();
    const issue = tracker.addIssue({ number: TICKET });
    const earlier = progressComment({
      version: "0.5.0",
      runId: "run-0",
      branch: BRANCH,
      rows: [
        {
          point: "implement",
          outcome: "⏸ rate limited",
          context: { tokens: 3_000 },
          durationMs: 60_000,
        },
      ],
    });
    issue.comments.push({ id: "42", body: `${earlier}${CLOUD_FOOTER}` });

    await progress(tracker, issue.comments).record({ point: "ci", outcome: "✅ passed" });

    expect(tracker.updatedComments[0]?.body).toBe(
      [
        earlier,
        `**ticket-runner** \`${VERSION}\` · run \`run-1\` · \`${BRANCH}\``,
        "",
        "| Stage | Outcome | Context | Duration |",
        "|---|---|---|---|",
        "| ci | ✅ passed | – | – |",
        "",
      ].join("\n"),
    );
  });

  it.each([
    ["Claude Code's", CLOUD_FOOTER],
    ["any other", "\n***\nposted by a bot | on behalf of someone\n"],
  ])("leaves one footer, at the end, after three Runs through a Host appending %s", async (_, footer) => {
    const tracker = new FakeTracker();
    tracker.footer = footer;
    const issue = tracker.addIssue({ number: TICKET });

    await progress(tracker, [], "run-1").record({ point: "implement", outcome: "⏸ rate limited" });
    await progress(tracker, issue.comments, "run-2").record({
      point: "implement",
      outcome: "⏸ rate limited",
    });
    const third = progress(tracker, issue.comments, "run-3");
    await third.record({ point: "implement", outcome: "✅ committed" });
    await third.record({ point: "ci", outcome: "✅ passed" });

    expect(tracker.comments).toHaveLength(1);
    expect([...body(tracker).matchAll(/run `(run-\d)`/g)].map((match) => match[1])).toEqual([
      "run-1",
      "run-2",
      "run-3",
    ]);
    expect(body(tracker).split(footer)).toHaveLength(2);
    expect(body(tracker).endsWith(`| ci | ✅ passed | – | – |\n${footer}`)).toBe(true);
  });

  it("keeps a comment an earlier version wrote as the first section, without the footer after its table", async () => {
    const tracker = new FakeTracker();
    const issue = tracker.addIssue({ number: TICKET });
    const single = [
      PROGRESS_MARKER,
      `**ticket-runner** · run \`run-0\` · \`${BRANCH}\``,
      "",
      "| Stage | Outcome | Turns | Duration |",
      "|---|---|---|---|",
      "| implement | ✅ committed | 7 | 20m |",
      "",
    ].join("\n");
    issue.comments.push({ id: "42", body: `${single}${CLOUD_FOOTER}` });

    await progress(tracker, issue.comments).record({ point: "verify", outcome: "❌ no verdict" });

    expect(body(tracker)).not.toContain("Generated by");
    expect(body(tracker).startsWith(`${single}\n**ticket-runner** \`${VERSION}\` · run \`run-1\``)).toBe(
      true,
    );
  });

  it("rewrites its own last section, footer and all, when it records more rows through a Host appending one", async () => {
    const tracker = new FakeTracker();
    tracker.footer = CLOUD_FOOTER;
    const issue = tracker.addIssue({ number: TICKET });
    await progress(tracker, [], "run-0").record({ point: "implement", outcome: "⏸ rate limited" });

    await progress(tracker, issue.comments).record({ point: "implement", outcome: "✅ committed" });
    // This Run reads the Ticket again, as it does on a second pass of it.
    const again = progress(tracker, issue.comments);
    await again.record({ point: "ci", outcome: "✅ passed" });
    await again.record({ point: "verify", outcome: "❌ 1 unmet" });

    expect(tracker.comments).toHaveLength(1);
    expect(body(tracker).match(/^\*\*ticket-runner\*\*/gm)).toHaveLength(2);
    expect(body(tracker).match(/run `run-1`/g)).toHaveLength(1);
    expect(body(tracker).split(CLOUD_FOOTER)).toHaveLength(2);
    expect(body(tracker)).toContain("| ci | ✅ passed | – | – |\n| verify | ❌ 1 unmet | – | – |");
  });

  it("names no Host in the header it writes", async () => {
    const tracker = new FakeTracker();
    tracker.addIssue({ number: TICKET });

    await progress(tracker).record({ point: "implement", outcome: "✅ committed" });

    const header = body(tracker).split("\n")[1];
    expect(header).toBe(`**ticket-runner** \`${VERSION}\` · run \`run-1\` · \`${BRANCH}\``);
  });

  it("starts a fresh comment when the Ticket is being taken back from a human", async () => {
    const tracker = new FakeTracker();
    const issue = tracker.addIssue({ number: TICKET });
    issue.comments.push({ id: "42", body: `${PROGRESS_MARKER}\nwhat the human read` });
    issue.comments.push({ id: "43", body: HANDOFF_MARKER + "\n**Handed off.**" });

    await progress(tracker, issue.comments).record({ point: "ci", outcome: "✅ passed" });

    // The table the human was handed stays as they read it; this Run reports
    // beside it rather than over it.
    expect(tracker.updatedComments).toEqual([]);
    expect(tracker.comments).toHaveLength(1);
  });

  it("carries on in the comment when the hand-off it finds is already history", async () => {
    const tracker = new FakeTracker();
    const issue = tracker.addIssue({ number: TICKET });
    issue.comments.push({ id: "42", body: `${PROGRESS_MARKER}\nwhat an earlier Run wrote` });
    issue.comments.push({
      id: "43",
      body: `${HANDOFF_MARKER}\n${HANDOFF_TAKEN_LINE}\n\n**Handed off.**`,
    });

    await progress(tracker, issue.comments).record({ point: "ci", outcome: "✅ passed" });

    // A hand-off a Run already took back is not a human holding the Ticket: this
    // is the same Run's second reading of the Ticket, or a later resume of it.
    expect(tracker.comments).toEqual([]);
    expect(tracker.updatedComments.map(({ id }) => id)).toEqual(["42"]);
  });

  it("starts a fresh comment when the one already there cannot be edited", async () => {
    const tracker = new FakeTracker();
    const issue = tracker.addIssue({ number: TICKET });
    issue.comments.push({ body: `${PROGRESS_MARKER}\nposted by something with no id` });

    await progress(tracker, issue.comments).record({ point: "implement", outcome: "✅ committed" });

    expect(tracker.comments).toHaveLength(1);
    expect(tracker.updatedComments).toEqual([]);
  });

  it("stops after a comment it cannot edit, rather than posting one per Stage", async () => {
    const tracker = new FakeTracker();
    tracker.addIssue({ number: TICKET });
    const lines: string[] = [];
    let posted = 0;
    tracker.comment = async (_number, body) => {
      posted += 1;
      return { body };
    };
    const recorder = new Progress({
      tracker,
      ticket: TICKET,
      version: VERSION,
      runId: "run-1",
      branch: BRANCH,
      comments: [],
      log: (line) => lines.push(line),
    });

    await recorder.record({ point: "implement", outcome: "✅ committed" });
    await recorder.record({ point: "ci", outcome: "✅ passed" });

    expect(posted).toBe(1);
    expect(lines).toEqual([`#${TICKET} posted a progress comment it cannot edit again`]);
  });

  it("swallows a tracker that will not take the comment, because a Ticket is not lost over one", async () => {
    const tracker = new FakeTracker();
    tracker.addIssue({ number: TICKET });
    const lines: string[] = [];
    tracker.comment = () => Promise.reject(new Error("502 from GitHub"));
    const recorder = new Progress({
      tracker,
      ticket: TICKET,
      version: VERSION,
      runId: "run-1",
      branch: BRANCH,
      comments: [],
      log: (line) => lines.push(line),
    });

    await expect(recorder.record({ point: "implement", outcome: "✅ committed" })).resolves.toBeUndefined();
    expect(lines).toEqual([`#${TICKET} could not write the progress comment: 502 from GitHub`]);
  });
});
